use leptos::prelude::*;

/// Inline SVG icon. Geometry is Lucide path data; the wrapper carries the
/// stroke settings so every icon on the site draws with the same weight.
#[component]
pub fn Icon(
    name: &'static str,
    #[prop(optional)] size: Option<u32>,
    #[prop(optional, into)] class: String,
) -> impl IntoView {
    let px = size.unwrap_or(16);
    let class = if class.is_empty() {
        "ico".to_string()
    } else {
        format!("ico {class}")
    };

    let brand = is_brand(name);
    let class = if brand {
        format!("{class} ico-brand")
    } else {
        class
    };

    view! {
        <svg
            class=class
            width=px
            height=px
            viewBox="0 0 24 24"
            fill=if brand { "currentColor" } else { "none" }
            stroke=if brand { "none" } else { "currentColor" }
            stroke-width="1.75"
            stroke-linecap="round"
            stroke-linejoin="round"
            aria-hidden="true"
            focusable="false"
            inner_html=icon_body(name)
        ></svg>
    }
}

/// Brand marks are Simple Icons glyphs: filled shapes, so they render with
/// `fill: currentColor` and no stroke instead of the Lucide stroke settings.
fn is_brand(name: &str) -> bool {
    matches!(
        name,
        "jellyfin" | "nextcloud" | "youtube-music" | "apple-music" | "soundcloud" | "spotify"
    )
}

